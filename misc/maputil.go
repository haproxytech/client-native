package misc //nolint: revive

import (
	"cmp"
	"iter"
	"maps"
	"slices"
)

// SortedByKey iterates m in ascending key order.
// Map order is random, so serializing a map without it makes output unstable.
func SortedByKey[K cmp.Ordered, V any](m map[K]V) iter.Seq2[K, V] {
	return func(yield func(K, V) bool) {
		for _, k := range slices.Sorted(maps.Keys(m)) {
			if !yield(k, m[k]) {
				return
			}
		}
	}
}
